import math
from math import pi, sqrt
print(math.pi, math.e, math.tau, pi, sqrt(16), math.sqrt(2))
print(math.floor(2.7), math.ceil(2.1), math.floor(-2.5), math.trunc(-2.7), math.floor(5))
print(math.sin(math.pi / 2), math.cos(0), math.atan2(1, 1), math.degrees(math.pi), math.radians(180))
print(math.hypot(3, 4), math.factorial(10), math.gcd(12, 18), math.log(8, 2), math.log10(1000), math.exp(0))
print(math.pow(2, 10), math.fabs(-3), math.isqrt(17), math.comb(5, 2))
